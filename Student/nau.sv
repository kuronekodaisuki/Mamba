// -----------------------------------------------------------------------------
// Nonlinear Approximation Unit (FastMamba-style, multi-mode exp / softplus)
//
//   exp(x)      = 2^(x*log2e) = 2^f >> s        x <= 0  (x > 0 is clamped to 0)
//                 t = x*log2e = -s + f,  s = -floor(t),  f in [0,1)
//                 2^f : 8-segment first-order approximation (no multiplier
//                 except c1*r, 17x13 bits)
//   softplus(x) = y + max(x,0),  y = exp(-|x|)    (symmetry: one exp core)
//
// Options (0 = as published, 1 = improved accuracy):
//   EXP_NEAR0 : exp(x) = 1 + x + x^2/2 for -1/16 < x <= 0. Keeps 1-exp(x)
//               accurate, which is the forgetting rate of the SSM state.
//   SP_ORDER2 : ln(1+y) = y - y^2/2 instead of y in softplus.
//
// Input and output share one fixed-point format (W_I bits, F_I fraction).
// Latency: 8 cycles, one input per cycle.
// Coefficient table generated by model/nau_golden.py --sv-table.
// -----------------------------------------------------------------------------
module nau #(
  parameter int W_I       = 24,
  parameter int F_I       = 18,
  parameter int F_L       = 14,       // fraction of the log2(e) constant
  parameter int LOG2E_Q   = 23637,    // round(log2(e) * 2^14); FastMamba 1.0111b = 23552
  parameter bit EXP_NEAR0 = 1'b0,
  parameter bit SP_ORDER2 = 1'b0
)(
  input  logic                  clk,
  input  logic                  rst_n,
  input  logic                  in_valid,
  input  logic                  in_softplus,   // 0: exp, 1: softplus
  input  logic signed [W_I-1:0] in_x,
  output logic                  out_valid,
  output logic signed [W_I-1:0] out_y
);
  localparam int F_C    = 16;              // fraction of 2^f and coefficients
  localparam int R_BITS = F_C - 3;         // 13
  localparam int F_T    = F_I + F_L;       // fraction of t
  localparam int W_T    = W_I + 17;        // W_I x 17-bit signed constant
  localparam int W_IP   = W_T - F_T;       // integer part of t
  localparam int W_E    = F_I + 2;         // exp result width (<= 2^F_I)

  localparam logic signed [16:0] LOG2E = 17'(LOG2E_Q);

  // synthesis translate_off
  initial if (F_T < F_C || F_I < 6)
    $fatal(1, "nau: unsupported fixed-point format");
  // synthesis translate_on

  // ---- stage 1: argument of the exp core (always <= 0) ----------------------
  logic                  v1, sp1;
  logic signed [W_I-1:0] neg1, pos1;

  always_ff @(posedge clk) begin
    v1  <= rst_n & in_valid;
    sp1 <= in_softplus;
    if (in_x < 0) begin
      neg1 <= in_x;
      pos1 <= '0;
    end else begin
      neg1 <= in_softplus ? -in_x : '0;      // exp mode clamps x > 0 to 0
      pos1 <= in_softplus ?  in_x : '0;
    end
  end

  // ---- stage 2: t = x * log2e, and x^2 for the near-zero path ---------------
  logic                  v2, sp2, nz2;
  logic signed [W_I-1:0] neg2, pos2;
  logic signed [W_T-1:0] t2;
  logic        [31:0]    sq2;
  logic signed [15:0]    neg_lo;

  assign neg_lo = neg1[15:0];   // exact whenever the near-zero path is taken

  always_ff @(posedge clk) begin
    v2   <= rst_n & v1;
    sp2  <= sp1;
    neg2 <= neg1;
    pos2 <= pos1;
    t2   <= neg1 * LOG2E;
    nz2  <= EXP_NEAR0 && (neg1 > -(W_I'(1) <<< (F_I - 4)));
    sq2  <= neg_lo * neg_lo;
  end

  // ---- stage 3: split t, table lookup, near-zero Taylor value ---------------
  logic        [F_C-1:0]  f16;
  logic        [2:0]      k;
  logic        [16:0]     c0, c1;
  logic signed [W_IP-1:0] tint;

  assign f16  = t2[F_T-1 -: F_C];
  assign k    = f16[F_C-1 -: 3];
  assign tint = t2[W_T-1:F_T];

  always_comb begin
    case (k)
      // generated by model/nau_golden.py --sv-table
      3'd0: begin c0 = 17'd65504; c1 = 17'd47452; end
      3'd1: begin c0 = 17'd71432; c1 = 17'd51747; end
      3'd2: begin c0 = 17'd77898; c1 = 17'd56430; end
      3'd3: begin c0 = 17'd84948; c1 = 17'd61538; end
      3'd4: begin c0 = 17'd92636; c1 = 17'd67107; end
      3'd5: begin c0 = 17'd101021; c1 = 17'd73181; end
      3'd6: begin c0 = 17'd110164; c1 = 17'd79805; end
      default: begin c0 = 17'd120135; c1 = 17'd87028; end
    endcase
  end

  logic                  v3, sp3, nz3;
  logic signed [W_I-1:0] pos3;
  logic        [W_IP-1:0] s3;
  logic        [16:0]    c0_3, c1_3;
  logic        [R_BITS-1:0] r3;
  logic        [W_E-1:0] e0_3;

  always_ff @(posedge clk) begin
    v3   <= rst_n & v2;
    sp3  <= sp2;
    nz3  <= nz2;
    pos3 <= pos2;
    s3   <= -tint;                                    // s = -floor(t) >= 0
    c0_3 <= c0;
    c1_3 <= c1;
    r3   <= f16[R_BITS-1:0];
    // 1 + x + x^2/2  (x = neg2, -2^-4 < x <= 0)
    e0_3 <= W_E'((W_I+1)'(1) <<< F_I) + W_E'(neg2) + W_E'((sq2 + (32'(1) << F_I)) >> (F_I + 1));
  end

  // ---- stage 4: 2^f = c0 + c1*r  (Q1.16) -------------------------------------
  logic                  v4, sp4, nz4;
  logic signed [W_I-1:0] pos4;
  logic        [W_IP-1:0] s4;
  logic        [17:0]    y4;
  logic        [W_E-1:0] e0_4;
  logic        [29:0]    prod3;

  assign prod3 = c1_3 * r3;

  always_ff @(posedge clk) begin
    v4   <= rst_n & v3;
    sp4  <= sp3;
    nz4  <= nz3;
    pos4 <= pos3;
    s4   <= s3;
    e0_4 <= e0_3;
    y4   <= 18'(c0_3) + 18'((prod3 + 30'(1 << (F_C-1))) >> F_C);
  end

  // ---- stage 5: shift right by s with rounding -------------------------------
  localparam int W_YO = 18 + F_I - F_C;    // y in Q(F_I)
  logic [W_YO-1:0] yo;
  logic [W_YO:0]   half, rsum;
  logic [W_E-1:0]  e_pwl;

  assign yo   = W_YO'(y4) << (F_I - F_C);
  assign half = (s4 == 0) ? '0 : ((W_YO+1)'(1) << (s4 - 1));
  assign rsum = (W_YO+1)'(yo) + half;
  assign e_pwl = (s4 > W_IP'(F_I + 2)) ? '0 : W_E'(rsum >> s4);

  logic                  v5, sp5;
  logic signed [W_I-1:0] pos5;
  logic        [W_E-1:0] e5;

  always_ff @(posedge clk) begin
    v5   <= rst_n & v4;
    sp5  <= sp4;
    pos5 <= pos4;
    e5   <= nz4 ? e0_4 : e_pwl;
  end

  // ---- stage 6: optional second-order softplus term --------------------------
  logic                  v6, sp6;
  logic signed [W_I-1:0] pos6;
  logic        [W_E-1:0] e6;
  logic        [2*W_E-1:0] esq6;

  always_ff @(posedge clk) begin
    v6   <= rst_n & v5;
    sp6  <= sp5;
    pos6 <= pos5;
    e6   <= e5;
    esq6 <= e5 * e5;
  end

  // ---- stage 7: second-order correction y - y^2/2 ---------------------------
  logic                  v7;
  logic signed [W_I-1:0] pos7;
  logic        [W_E-1:0] ycorr7;

  always_ff @(posedge clk) begin
    v7     <= rst_n & v6;
    pos7   <= pos6;
    ycorr7 <= (SP_ORDER2 && sp6)
            ? e6 - W_E'((esq6 + (2*W_E)'(1 << F_I)) >> (F_I + 1))
            : e6;
  end

  // ---- stage 8: y + max(x,0), saturate ---------------------------------------
  // Both terms are >= 0 (ycorr7 <= 1.0, pos7 = max(x,0) < 2^(W_I-1)), so the
  // sum fits W_I unsigned bits and only the upper bound can be exceeded:
  // overflow is just its MSB. Same result as saturate(), one carry chain less.
  logic [W_I-1:0] sum8;

  assign sum8 = W_I'(ycorr7) + W_I'(pos7[W_I-2:0]);

  always_ff @(posedge clk) begin
    out_valid <= rst_n & v7;
    out_y     <= sum8[W_I-1] ? {1'b0, {(W_I-1){1'b1}}} : sum8;
  end
endmodule
