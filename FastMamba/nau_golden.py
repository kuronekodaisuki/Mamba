#!/usr/bin/env python3
"""Bit-accurate golden model of nau.sv / ssm_discretize.sv (FastMamba-style).

  exp(x)      = 2^(x*log2e) = 2^f >> s       (x <= 0, floor split t = -s + f)
  2^f, f in [0,1) : 8-segment first-order (linear) approximation
  softplus(x) = exp(x)          (x <= 0)
              = x + exp(-x)     (x >  0)     (symmetry, reuses the exp core)

Usage:
  python3 model/nau_golden.py --sv-table          # print the SV coefficient case
  python3 model/nau_golden.py --out vec           # accuracy report + test vectors
"""
import argparse
import os
import numpy as np

# ---- formats (must match nau.sv / ssm_discretize.sv parameters) ----
W_I, F_I = 24, 18          # NAU input  (Q5.18)
W_O, F_O = 24, 18          # NAU output (Q5.18)
F_L = 14                   # log2(e) constant fraction
LOG2E_Q = round(np.log2(np.e) * (1 << F_L))   # 23637 ; FastMamba's 1.0111b = 23552
F_T = F_I + F_L            # fraction of t = x*log2e
F_C = 16                   # coefficient / 2^f fraction
SEG_BITS = 3               # 8 segments
R_BITS = F_C - SEG_BITS    # 13

W_RAW, F_RAW = 16, 10      # dt_raw, dt_bias
W_AA, F_AA = 16, 10        # A (negative)
W_DA, F_DA = 18, 16        # dA output = ssm_scan_unit W_A/F_A

# Options (0 = as published in FastMamba, 1 = improved; must match nau.sv)
EXP_NEAR0 = 0              # exp(x) = 1 + x + x^2/2 for -1/16 < x <= 0
SP_ORDER2 = 0              # softplus: ln(1+y) = y - y^2/2 instead of y


def sat(v, w):
    return int(min(max(v, -(1 << (w - 1))), (1 << (w - 1)) - 1))


def rsr(v, s):
    return v if s == 0 else (v + (1 << (s - 1))) >> s


def coeffs():
    """Chord through each segment, shifted down by half the max error."""
    c0, c1 = [], []
    for k in range(1 << SEG_BITS):
        a, b = k / 8, (k + 1) / 8
        slope = (2 ** b - 2 ** a) * 8
        f = np.linspace(a, b, 2001)
        err = (2 ** a + slope * (f - a)) - 2 ** f          # >= 0 (convex)
        off = err.max() / 2
        c0.append(round((2 ** a - off) * (1 << F_C)))
        c1.append(round(slope * (1 << F_C)))
    return c0, c1


C0, C1 = coeffs()


def exp_core(neg):
    """neg <= 0 in Q(F_I). Returns exp(neg) in Q(F_O)."""
    if EXP_NEAR0 and neg > -(1 << (F_I - 4)):
        return (1 << F_O) + neg + rsr(neg * neg, F_I + 1)
    t = neg * LOG2E_Q                         # Q(F_T), <= 0
    s = -(t >> F_T)                            # floor -> s >= 0
    f16 = (t & ((1 << F_T) - 1)) >> (F_T - F_C)
    k, r = f16 >> R_BITS, f16 & ((1 << R_BITS) - 1)
    y = C0[k] + rsr(C1[k] * r, F_C)           # 2^f in Q1.16
    yo = y << (F_O - F_C)                      # Q(F_O)
    return 0 if s > F_O + 2 else rsr(yo, s)


def nau(mode_softplus, x):
    if not mode_softplus:                      # exp mode: clamp x > 0 to 0
        return sat(exp_core(min(x, 0)), W_O)
    y = exp_core(-abs(x))                      # e^(-|x|)
    if SP_ORDER2:
        y = y - rsr(y * y, F_O + 1)            # ln(1+y) ~ y - y^2/2
    return sat(y + (x if x > 0 else 0), W_O)


def discretize(dt_raw, dt_bias, A):
    z = sat((dt_raw + dt_bias) << (F_I - F_RAW), W_I)
    delta = nau(True, z)                               # Q(F_O)
    da_in = sat(rsr(delta * A, F_O + F_AA - F_I), W_I)  # dt*A -> Q(F_I)
    e = nau(False, da_in)
    dA = sat(rsr(e, F_O - F_DA), W_DA)
    return delta, dA


def sv_table():
    print("      // generated by model/nau_golden.py --sv-table")
    for k in range(8):
        print(f"      3'd{k}: begin c0 = 17'd{C0[k]}; c1 = 17'd{C1[k]}; end")


def report():
    print(f"LOG2E_Q = {LOG2E_Q}  coeffs c0={C0} c1={C1}")
    xs = np.linspace(-12, 0, 4001)
    q = [nau(False, int(round(x * (1 << F_I)))) / (1 << F_O) for x in xs]
    rel = np.abs(np.array(q) - np.exp(xs)) / np.exp(xs)
    print(f"exp      x in [-12,0]   max rel err {rel.max():.2e}  "
          f"(x in [-4,0]: {rel[xs >= -4].max():.2e})")
    xs = np.linspace(-10, 10, 4001)
    q = np.array([nau(True, int(round(x * (1 << F_I)))) / (1 << F_O) for x in xs])
    ref = np.log1p(np.exp(xs))
    rel = np.abs(q - ref) / ref
    print(f"softplus x in [-10,10]  max abs err {np.abs(q-ref).max():.3f} (at x={xs[np.abs(q-ref).argmax()]:.2f})")
    for lo in (-7, -4, -2):
        m = (xs >= lo - 1e-9) & (xs <= lo + 1)
        print(f"         x in [{lo},{lo+1}]  max rel err {rel[m].max():.2e}")
    # decay-rate precision: 1 - exp(dt*A) for small dt*A
    for fi in (10, 18):
        errs = []
        for da in (-1e-3, -3e-3, -1e-2, -0.1, -1.0):
            xq = int(round(da * (1 << fi))) << (F_I - fi) if fi <= F_I else 0
            v = nau(False, xq) / (1 << F_O)
            errs.append(abs((1 - v) - (1 - np.exp(da))) / (1 - np.exp(da)))
        print(f"input frac={fi:2d}: rel err of (1-dA) at dt*A=-1e-3..-1 : "
              + "  ".join(f"{e:.1e}" for e in errs))


def write_vectors(out, seed=0):
    os.makedirs(out, exist_ok=True)
    rng = np.random.default_rng(seed)
    m24 = (1 << 24) - 1
    # NAU: sweep + random, both modes
    xs = list(np.linspace(-20, 20, 801)) + list(rng.uniform(-31, 31, 1199))
    with open(f"{out}/nau.hex", "w") as f:
        n = 0
        for mode in (0, 1):
            for x in xs:
                xi = sat(int(round(x * (1 << F_I))), W_I)
                f.write(f"{mode:x} {xi & m24:06x} {nau(bool(mode), xi) & m24:06x}\n")
                n += 1
    # discretize: Mamba2-like ranges
    with open(f"{out}/disc.hex", "w") as f:
        for _ in range(2000):
            raw = sat(int(round(rng.normal(-1, 3) * (1 << F_RAW))), W_RAW)
            bias = sat(int(round(np.log(np.expm1(rng.uniform(1e-3, 0.1))) * (1 << F_RAW))), W_RAW)
            A = sat(int(round(-rng.uniform(1, 16) * (1 << F_AA))), W_AA)
            d, dA = discretize(raw, bias, A)
            f.write(f"{raw & 0xffff:04x} {bias & 0xffff:04x} {A & 0xffff:04x} "
                    f"{d & m24:06x} {dA & 0x3ffff:05x}\n")
    print(f"vectors: {n} NAU, 2000 discretize -> {out}/")


if __name__ == "__main__":

    ap = argparse.ArgumentParser()
    ap.add_argument("--sv-table", action="store_true")
    ap.add_argument("--out", default=None)
    ap.add_argument("--improved", action="store_true",
                    help="EXP_NEAR0=1, SP_ORDER2=1 (set the same in nau.sv)")
    a = ap.parse_args()
    if a.improved:
        EXP_NEAR0 = SP_ORDER2 = 1
    if a.sv_table:
        sv_table()
    else:
        report()
        if a.out:
            write_vectors(a.out)
